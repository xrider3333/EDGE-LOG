def test_status_missing_newline_and_bom(tdir):
    with open(str(tdir / "STATUS.md"), "wb") as f:
        f.write(b"\xef\xbb\xbf| Q1 | one | \xe2\x9c\x85 | x |")
    T.add_task("t", "b", "ENGUQ")
    raw = open(str(tdir / "STATUS.md"), "rb").read()
