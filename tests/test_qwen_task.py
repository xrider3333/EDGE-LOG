def test_check_minutes_from_stamps_and_override(tdir, vs):
    _task(tdir, GOOD_BLOCK)
    lines = []
    T.check_task(12, now="2026-10-31T10:00-07:00", out=lines.append)
    T.check_task(12, now="2026-10-31T10:07-07:00", out=lines.append)
    txt = _r(T.find(12))
    assert txt.count("CHECK_START:") == 1 and "CHECK_START: 2026-10-31T10:00-07:00" in txt
    assert txt.count("CHECK_END:") == 1 and "CHECK_END: 2026-10-31T10:07-07:00" in txt
    assert "Claude check 7.0 min" in lines[-1]
    vs_txt = _r(vs)
    assert vs_txt.count("| Q12 |") == 1 and "| 45.4 | 7.0 | PASS |" in vs_txt     # row replaced, not duplicated
    assert vs_txt.count("\r\n") > 3 and "\n" not in vs_txt.replace("\r\n", "")      # kept CRLF
    T.check_task(12, minutes=3, now="2026-10-31T10:30-07:00", out=lines.append)
    assert "Claude check 3.0 min" in lines[-1] and "| 45.4 | 3.0 | PASS |" in _r(vs)
    assert T.main(["check", "12", "--minutes", "2.5"]) == 0 and "| 45.4 | 2.5 | PASS |" in _r(vs)
