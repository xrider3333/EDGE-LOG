TODAY = datetime.date.today().isoformat()
STATUS = ("# Qwen task board  (⭕ open · 🟡 Qwen working)\r\n| # | Task | Status | Note |\r\n|---|------|--------|------|\r\n"
          "| Q1 | one | ✅ | x |\r\n| Q12 | twelve | ⭕ | small, read-only |\r\n")


def _w(p, s):
    with open(p, "wb") as f:
        f.write(s.encode("utf-8"))


def _r(p):
    with open(p, "rb") as f:
        return f.read().decode("utf-8")


